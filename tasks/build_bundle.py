"""Build a single-file, Kaggle-pushable bundle of a task.

`kaggle b t push -f FILE` uploads one file, so the shared boundary_common
modules are inlined ahead of the task code. Package-relative imports are
removed; everything else is kept as written.

    python tasks/build_bundle.py t01_file_inspection
    -> dist/boundary_t01_file_inspection.py
"""
import ast
import re
import sys
from pathlib import Path

TASKS = Path(__file__).resolve().parent
DIST = TASKS.parent / "dist"
# dependency order: later modules may use names from earlier ones
COMMON_MODULES = ("trace", "usage", "record", "sandbox", "models")


# kaggle_benchmarks reads the Model Proxy env at import time, and the inlined
# modules import it before the task code does, so .env must load first.
DOTENV_FIRST = """
# %%
try:
    from dotenv import find_dotenv, load_dotenv

    load_dotenv(find_dotenv())
except ImportError:  # not needed on Kaggle
    pass
"""


def strip_internal_imports(source: str) -> str:
    """Drop `from .x import ...` and `from boundary_common import ...` (any length)."""
    lines = source.splitlines(keepends=True)
    drop = set()
    for node in ast.parse(source).body:
        if isinstance(node, ast.ImportFrom) and (node.level > 0 or node.module == "boundary_common"):
            drop.update(range(node.lineno - 1, node.end_lineno))
    return "".join(l for i, l in enumerate(lines) if i not in drop)


def build(task_module: str) -> Path:
    parts = [
        f"# AUTO-GENERATED by tasks/build_bundle.py from tasks/{task_module}.py. Do not edit.\n",
        DOTENV_FIRST,
    ]
    for name in COMMON_MODULES:
        src = (TASKS / "boundary_common" / f"{name}.py").read_text(encoding="utf-8")
        parts.append(f"\n# %%\n# ---- boundary_common/{name}.py ----\n{strip_internal_imports(src)}")
    task_src = (TASKS / f"{task_module}.py").read_text(encoding="utf-8")
    task_src = re.sub(r"^sys\.path\.insert\(0, .*__file__.*\)\n", "", task_src, flags=re.M)
    parts.append("\n" + strip_internal_imports(task_src))
    bundle = "".join(parts)
    compile(bundle, task_module, "exec")  # fail here, not on the server
    assert "__file__" not in bundle.replace("`__file__`", ""), "bundle must not use __file__"
    DIST.mkdir(exist_ok=True)
    out = DIST / f"boundary_{task_module}.py"
    out.write_text(bundle, encoding="utf-8", newline="\n")
    return out


if __name__ == "__main__":
    print(build(sys.argv[1] if len(sys.argv) > 1 else "t01_file_inspection"))
